"""
================================================================================
FILE: backend/tests/test_limit_message_metadata.py
SUMMARY
    Header and streaming refusals capture actual caps without mutating a project.
BASIC IDEA
    Compare each guard's legacy detail and descriptor using a synthetic project
    and small patched caps. A lying length exercises the route's second guard.
INPUTS / INPUT SOURCES
    In-process TestClient, generated bytes and current cap configuration.
EXPECTED OUTPUT
    Identical metadata at both boundaries, preserved state and exact cap values.
================================================================================
"""
import io
import pytest
from app.routers import data, ontologies, projects
from app import tabular
from test_router_message_metadata import client, context, state

CASES = [
    ("upload", "request.file_limit"),
    ("source", "request.file_limit"),
    ("layout", "request.layout_limit"),
    ("nodes", "request.nodes_limit"),
    ("mapping", "data.mapping_limit"),
    ("data", "data.file_limit"),
    ("imports", "imports.total_file_limit"),
]


@pytest.mark.parametrize("kind,code", CASES)
def test_declared_and_streaming_limits_share_actual_facts(context, monkeypatch, kind, code):
    limit = 64
    monkeypatch.setattr(ontologies, "CHUNK_BYTES", 8)
    if kind in {"upload", "source"}:
        monkeypatch.setattr(ontologies, "MAX_UPLOAD_BYTES", limit)
        expected = ontologies.too_large_detail(limit, "SEMANTIC_STUDIO_MAX_UPLOAD_BYTES")
    elif kind == "layout":
        monkeypatch.setattr(projects, "LAYOUT_MAX_BYTES", limit)
        expected = projects.LAYOUT_TOO_LARGE
    elif kind == "nodes":
        monkeypatch.setattr(ontologies, "NODES_MAX_BYTES", limit)
        expected = ontologies.NODES_TOO_LARGE
    elif kind == "mapping":
        monkeypatch.setattr(data, "PATCH_MAX_BYTES", limit)
        expected = data.PATCH_TOO_LARGE
    elif kind == "data":
        monkeypatch.setattr(tabular, "MAX_BYTES", limit)
        expected = {"message": data.FILE_TOO_LARGE, "kind": "too-large"}
    else:
        monkeypatch.setattr(ontologies.imports_mod, "MAX_TOTAL_BYTES", limit)
        expected = ontologies.IMPORT_FILES_TOO_LARGE
    pid, oid, sid = context["pid"], context["oid"], context["sid"]
    methods = {"upload": "POST", "source": "PUT", "layout": "PUT", "nodes": "POST", "mapping": "PATCH", "data": "POST", "imports": "POST"}
    paths = {
        "upload": "/api/ontologies/upload",
        "source": f"/api/projects/{pid}/documents/model/source",
        "layout": f"/api/projects/{pid}/documents/model/layout",
        "nodes": f"/api/ontologies/{oid}/nodes",
        "mapping": f"/api/projects/{pid}/data/{sid}",
        "data": f"/api/projects/{pid}/data/inspect",
        "imports": f"/api/ontologies/{oid}/imports/files",
    }
    # Source reads enforce the upload cap too; reading the state here must not
    # itself send a write through the patched cap.
    before = state(context)
    responses = []
    for header in [str(1024 * 1024), "0"]:
        kwargs = {"headers": {"content-length": header}}
        if kind in {"upload", "data", "imports"}:
            field = "files" if kind == "imports" else "file"
            kwargs["files"] = {field: ("synthetic.ttl", io.BytesIO(b"x" * 65), "text/turtle")}
        else:
            kwargs["content"] = b"x" * 65
        response = client.request(methods[kind], paths[kind], **kwargs)
        assert response.status_code == 413, response.text
        body = response.json()
        assert body["detail"] == expected
        responses.append(body)
    args = {"limit": limit}
    if kind in {"upload", "source"}:
        args["variable"] = "SEMANTIC_STUDIO_MAX_UPLOAD_BYTES"
    for body in responses:
        assert body.get("uiMessage") == {"code": code, "args": args}
    assert state(context) == before


def test_a_configured_limit_beyond_js_precision_is_not_rounded():
    limit = 2**60 + 1
    text = ontologies.too_large_detail(limit, "SYNTHETIC_CAP")
    assert text.ui_message == {"code": "request.file_limit", "args": {"limit": str(limit), "variable": "SYNTHETIC_CAP"}}


@pytest.mark.parametrize("kind,code", [("file", "parse.file_timeout"), ("text", "parse.text_timeout")])
def test_timeout_source_facts_reach_the_http_response(context, monkeypatch, kind, code):
    from app import editing
    import importlib
    store_module = importlib.import_module("app.store")
    seconds = 1234.5
    observed = []

    class TimedOut:
        def result(self, timeout):
            observed.append(timeout)
            raise TimeoutError()

    class Executor:
        def __init__(self, **kwargs):
            pass

        def __enter__(self):
            return self

        def __exit__(self, *args):
            return False

        def submit(self, *args):
            return TimedOut()

        def shutdown(self, **kwargs):
            pass

    monkeypatch.setattr(ontologies, "PARSE_TIMEOUT_SECONDS", seconds)
    monkeypatch.setattr(store_module if kind == "file" else editing, "ThreadPoolExecutor", Executor)
    before = state(context)
    if kind == "file":
        response = client.post("/api/ontologies/upload", files={"file": ("synthetic.ttl", b"@prefix ex: <https://example.test/> .", "text/turtle")})
        expected = f"This file took longer than {seconds:g} seconds to parse and was stopped. You can raise the limit with SEMANTIC_STUDIO_PARSE_TIMEOUT."
    else:
        response = client.put(f"/api/projects/{context['pid']}/documents/model/source", json={"text": "<https://example.test/s> <https://example.test/p> <https://example.test/o> ."})
        expected = f"This text took longer than {seconds:g} seconds to parse and was stopped."
    assert response.status_code == 504, response.text
    assert response.json()["detail"] == expected
    assert observed == [seconds]
    assert response.json().get("uiMessage") == {"code": code, "args": {"seconds": seconds}}
    assert state(context) == before



def test_unknown_timeout_keeps_legacy_exception_and_http_detail(context, monkeypatch):
    from app.store import ParseTimeout
    error = ParseTimeout("Unknown timeout <img>{seconds}")
    assert error.args == ("Unknown timeout <img>{seconds}",)
    assert str(error) == error.args[0]
    assert error.ui_message is None

    def fail(**kwargs):
        raise error

    monkeypatch.setattr(ontologies.store, "add", fail)
    response = client.post("/api/ontologies/upload", files={"file": ("synthetic.ttl", b"x", "text/turtle")})
    assert response.status_code == 504
    assert response.json() == {"detail": str(error)}
